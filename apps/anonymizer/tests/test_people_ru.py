"""People in Russian text."""

import pytest

from anonymizer import people
from anonymizer.detector import detect
from tests.helpers import assert_clear, assert_masked


@pytest.mark.parametrize("text,fragment", [
    ("Вчера поругалась с мамой Людой", "Людой"),
    ("мама люда опять звонила", "люда"),
    ("Муж серёжа против терапии", "серёжа"),
    ("Наташка опять не отвечает", "Наташка"),
    ("с Петровой из бухгалтерии не общаюсь", "Петровой"),
    ("Записалась к Крапивину на среду", "Крапивину"),
    ("Свекровь Вероника Шмыгло приехала", "Вероника Шмыгло"),
    ("Мой начальник Петров Игорь Викторович кричит", "Петров Игорь Викторович"),
    ("Классная руководительница Ольга Петровна вызвала", "Ольга Петровна"),
    ("Островская В.О. постоянно жалуется", "Островская В.О."),
    ("И. И. Иванов подписал", "И. И. Иванов"),
    ("Мы с колей расстались весной", "колей"),
    ("Написала Юле вечером", "Юле"),
    ("Бабушка Зина живёт одна", "Зина"),
    ("Со мной работала Резеда Ринатовна", "Резеда Ринатовна"),
    ("Отец, Игорь Викторович, всегда был холоден", "Игорь Викторович"),
    ("Подруга Лена и её муж Вадик зовут на дачу", "Вадик"),
    ("Когда Тёма плачет, я теряюсь", "Тёма"),
])
def test_person_is_masked(text, fragment):
    assert_masked(text, fragment)


@pytest.mark.parametrize("text,fragment", [
    ("Вера в себя появилась не сразу", "Вера"),
    ("Надежда есть, но сил нет", "Надежда"),
    ("Любовь к себе — не эгоизм", "Любовь"),
    ("ребёнок не спит без света", "света"),
    ("ИНН нужен для вычета", "ИНН"),
    ("Мама всегда говорила, что я ничего не добьюсь", "Мама"),
    ("Подружка пишет каждый вечер", "Подружка"),
    ("Живу в городе, где никого не знаю", "городе"),
    ("ПОМОГИТЕ мне пожалуйста", "ПОМОГИТЕ"),
    ("В марте будет год, как я не пью", "марте"),
    ("Слава богу, всё обошлось", "богу"),
])
def test_not_a_person(text, fragment):
    assert_clear(text, fragment)


@pytest.mark.parametrize("surface,canon", [
    ("Петровой", "Петрова"),
    ("Петрову Игорю Викторовичу", "Петров Игорь Викторович"),
    ("Людой", "Люда"),
    ("Юле", "Юля"),
    ("Серёже", "Серёжа"),
    ("Наталье Сергеевне", "Наталья Сергеевна"),
    ("Александрой", "Александра"),
    ("Александром", "Александр"),
])
def test_canonical_form_keeps_gender(surface, canon):
    assert people.canonical(surface)[0] == canon


def test_same_person_same_key_in_any_case():
    keys = {people.canonical(s)[1] for s in ("Люда", "Люды", "Люде", "Люду", "Людой")}
    assert keys == {"люда"}


def test_geography_marker_with_dot_only():
    # "с" without a dot is a preposition, not "село"
    assert_masked("договорились с Кравцовым на завтра", "Кравцовым")
    d = detect("живу в пос. Орловка давно")
    assert all(s.kind.value != "PERSON" for s in d.spans)
    assert_masked("живу в пос. Орловка давно", "Орловка")
