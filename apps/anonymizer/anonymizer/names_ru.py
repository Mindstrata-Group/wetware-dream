# Names that are also everyday words. They count as a person only when
# written with a capital letter mid-sentence or right after a relation cue.
AMBIGUOUS = frozenset(morph.norm(w) for w in """
вера надежда любовь роза лилия мира слава лев ян ева лада нина мила ника лиса
кит серый марк дэн оскар рая тома гера ася тата кира валя тоня яна лара лора
майя маня роман адам эрик рина лина зина аля жанна варя ната уля эля агата
""".split())


def _parse_raw():
    full: dict[str, str] = {}
    dim: dict[str, str] = {}
    for line in _RAW.strip().splitlines():
        name, g, rest = line.split(":")
        gender = "masc" if g == "m" else "femn"
        full[name] = gender
        for d in filter(None, rest.split(",")):
            dim.setdefault(d, gender)
    return full, dim


FULL, DIMINUTIVE = _parse_raw()


@lru_cache(maxsize=1)
def form_index() -> dict[str, tuple[str, str]]:
    """normalized case form -> (nominative, gender) for every listed name."""
    index: dict[str, tuple[str, str]] = {}
    # A listed nominative always maps to itself: "Александра" is a name of
    # its own, not the genitive of "Александр".
    for table in (FULL, DIMINUTIVE):
        for nom, gender in table.items():
            index.setdefault(morph.norm(nom), (nom, gender))
    for table in (FULL, DIMINUTIVE):
        for nom, gender in table.items():
            for f in decline.forms(nom, "Name", gender):
                index.setdefault(f, (nom, gender))
    return index


def lookup(word: str) -> tuple[str, str] | None:
    """(nominative, gender) if the word is a case form of a listed first name."""
    return form_index().get(morph.norm(word))


def gender_of_first_name(word: str) -> str | None:
    hit = lookup(word)
    return hit[1] if hit else None
